const DOCS: Record<string, { title: string; content: () => ReactNode }> = {
  policy: {
    title: "Политика обработки персональных данных сервиса «Для мам»",
    content: PolicyContent,
  },
  consent: {
    title: "Согласие на обработку персональных данных",
    content: ConsentContent,
  },
  agreement: {
    title: "Пользовательское соглашение сервиса «Для мам»",
    content: AgreementContent,
  },
};

export function DocPage() {
  const { docType } = useParams<{ docType: string }>();
  const doc = docType ? DOCS[docType] : null;

  if (!doc) {
    return (
      <div className="card">
        <p className="muted">Документ не найден.</p>
        <Link to="/" style={{ marginTop: 12, display: "inline-block" }}>На главную</Link>
      </div>
    );
  }

  const Content = doc.content;
  return (
    <DocLayout title={doc.title}>
      <Content />
    </DocLayout>
  );
}
